"""学習ワーカーが読み込む外部入力の資源上限（REQ-39）を 1 箇所に集約する。

**暫定値であることの注記**: 以下はすべて学習ワーカー固有の暫定値であり、
推論ガード層（Rust 側）向けに REQ-39 が定義する資源上限とは別物として扱う
（REQ-39 は推論ガード層向けの暫定値を定義しており、本ワーカーへの適用範囲は
オーナー確認待ちの論点。ここでは学習ワーカー固有の値として暫定的に定める。
値そのものもレビューで指摘された妥当な水準の暫定案であり、オーナー確認前提）。
"""

from __future__ import annotations

#: 学習リクエスト JSON ファイルの最大バイト数。
MAX_REQUEST_BYTES = 1 * 1024 * 1024

#: 学習データ（JSONL）ファイルの最大バイト数（累積読み取りバイト数で判定する）。
MAX_TRAIN_DATA_BYTES = 64 * 1024 * 1024

#: 学習データの最大件数（行数ではなく、検証を通過した examples の件数）。
MAX_TRAIN_EXAMPLES = 200_000

#: 学習データ 1 行あたりの最大バイト数（JSON パース・NFKC 正規化の前に検査する）。
MAX_TRAIN_LINE_BYTES = 64 * 1024

#: label_order の最小・最大件数。
MIN_LABELS = 2
MAX_LABELS = 1024

#: 1 ラベルあたりの最大 UTF-8 バイト数。
MAX_LABEL_BYTES = 256

#: max_bytes（バイト入力の最大長）の許容範囲。
MIN_MAX_BYTES = 1
MAX_MAX_BYTES = 4096

#: seed の許容範囲（`mx.random.seed`・`numpy.random.default_rng` が受け付ける
#: 非負 32 bit 符号なし整数の範囲に合わせる）。
MIN_SEED = 0
MAX_SEED = 2**32 - 1

# --------------------------------------------------------------------------
# ジョブ全体の資源上限（REQ-39: 学習時間・メモリ）。`budget.py::ResourceBudget`
# が検査する。リクエストの任意項目 `time_limit_seconds`・`rss_limit_bytes` で
# 下げることはできるが、ここでの上限を超える値は拒否する（invalid_request）。
# --------------------------------------------------------------------------

#: 学習ジョブ 1 回あたりの壁時計時間の既定・上限（秒）。REQ-18 の候補探索予算
#: （既定 1 時間の目安。PoC-10 `train_mlx.py` の `BUDGET = 3600.0` と同じ水準）
#: をそのまま学習ワーカー全体の既定上限として採用する。
MAX_TRAIN_WALL_SECONDS = 3600

#: 学習ジョブ 1 回あたりのプロセス RSS（常駐メモリ量）の既定・上限（bytes）。
MAX_TRAIN_RSS_BYTES = 8 * 1024 * 1024 * 1024

#: 学習ループが回す総ステップ数（examples 件数 × epochs）の上限。学習開始前に
#: 見積もりで検査し、実測を待たずに拒否する（1 ステップも回さずに reject できる）。
MAX_TRAIN_SAMPLE_STEPS = 20_000_000

#: 学習データ全体を数値トークン列へエンコードした際の総トークン数
#: （examples 件数 × max_bytes の見積もり）の上限。エンコード結果を Python の
#: リストのリストとして保持すると、この見積もりを経ずに際限なくメモリを
#: 確保してしまうため、エンコード前に検査する（P0-1）。
MAX_TRAIN_TOTAL_TOKENS = 50_000_000

#: 学習済みモデルの重み（float32 換算）の総バイト数の上限。REQ-30 の配布
#: パッケージ容量目安（約 40MB）を、学習側でも早期に検査する目的で準用する
#: （長時間・大量メモリを要する学習・ONNX 書き出しを、開始前に断念させる）。
MAX_MODEL_BYTES = 40 * 1024 * 1024

# --------------------------------------------------------------------------
# kind="c3" のアーキテクチャ・ハイパーパラメータ上限。
#
# 本来は「新しい kind を追加する際に共通コア・既存の種類の実装を改変しない」
# （拡張点の閉じ方）という方針上、kind 固有の上限は `kinds/c3.py` 側に置く方が
# 望ましい。ここへ集約しているのはレビュー指摘（「資源上限は名前付き定数として
# limits.py へ集約する」）に従うためで、C1 等の追加時にこのセクションが
# 肥大化するようなら kind ごとの上限モジュールへ分割することを検討する。
# --------------------------------------------------------------------------
MAX_C3_EMB = 1024
MAX_C3_FILTERS = 1024
MIN_C3_WIDTHS = 1
MAX_C3_WIDTHS = 8
MAX_C3_WIDTH_VALUE = 31
MAX_C3_EPOCHS = 1000
MAX_C3_BATCH_SIZE = 4096
MAX_C3_LR = 1.0
MAX_C3_WEIGHT_DECAY = 1.0

# --------------------------------------------------------------------------
# kind="c1" のハイパーパラメータ・語彙構築の上限（TASK-19.2。REQ-19・REQ-39）。
# 上記 C3 セクションと同じ考え方（新しい kind を追加する際に既存の種類の実装を
# 改変しない拡張点の閉じ方）で、c1 固有の上限を独立したセクションとしてここへ
# 追加する。
# --------------------------------------------------------------------------

#: n-gram の n の許容上限。base-257 キー化（`kinds/c1.py::_ngram_keys`）は
#: `257 ** n` の int64 演算に依存するため、n=7 でも `257**7 ≈ 1.2e17` は
#: int64 の範囲（最大 ≈ 9.2e18）に十分収まる。7 を超える n は語彙構築の
#: 計算量・メモリ見積もりが不透明になるため許可しない。
MAX_C1_NGRAM = 7

#: `min_df`（文書頻度の下限）の許容範囲。
MIN_C1_MIN_DF = 1
MAX_C1_MIN_DF = MAX_TRAIN_EXAMPLES

#: `max_features`（語彙の最大列数）の許容範囲。既定値 200,000 の 10 倍を上限とする
#: （REQ-30 の配布パッケージ容量目安をモデルサイズ側の `check_model_bytes` で
#: 別途検査するため、ここでの上限はモデル構築前の一次的な妥当性検査に留める）。
MAX_C1_MAX_FEATURES = 2_000_000

#: sklearn 風の正則化強度 `C`（大きいほど正則化が弱い）の許容範囲。
#: 下限は罰則係数 `0.5 / (C * n_examples)` が float32 でも有限に収まるための値
#: （C=1e-6・n_examples=1 で係数 5e5）。これより小さい C は係数が発散し、設定
#: 誤りが `training_diverged` に化けるため `invalid_config` で拒否する。
MIN_C1_C = 1.0e-6
MAX_C1_C = 1.0e6

MAX_C1_EPOCHS = 1000
MAX_C1_BATCH_SIZE = 4096
MAX_C1_LR = 10.0

#: 語彙構築中（`kinds/c1.py::_build_vocabulary`）に、文書頻度の集計配列
#: （`(n, base257 key)` を束ねた結合キーと、その出現件数を保持する 2 本の
#: numpy 配列）が保持しうる相異なるキー数の上限。numpy によるベクトル化抽出
#: （チャンクごとの `np.unique` によるマージ）はこのキー数そのものを抑制
#: しないため、病的な入力（極端に長い・多様なバイト列を大量に含む学習データ）
#: でも配列が際限なく増え続けないよう、学習開始前に見積もった上限とは別に、
#: チャンク処理のたびに実測値で打ち切る（1 エントリあたり int64 配列 2 本
#: （結合キー・出現件数）で 16 bytes と見積もり、本上限でも 1 GiB 未満に
#: 収まる）。
MAX_C1_VOCAB_CANDIDATES = 5_000_000

#: 疎特徴量（列インデックス・値の対）を文書ごとに固定幅へ詰め物する際の、
#: 全文書分の要素総数（`examples 件数 × 詰め物後の疎行の幅`）の上限。
#: `check_total_tokens` と同様に、確保前の見積もりで検査する（P0-1 の考え方の
#: 準用）。
MAX_C1_SPARSE_ELEMENTS = 200_000_000

#: ミニバッチのフォワード（`TfidfLogReg.__call__` の `mx.take` による gather
#: `(B, nnz, K)` とそれに続く要素積）が確保しうる要素数（`batch_size × max_nnz
#: × n_classes`）の上限（セキュリティ監査 P0）。`MAX_C1_SPARSE_ELEMENTS`・
#: `check_model_bytes`・`check_sample_steps`・`check_total_tokens` はいずれも
#: 「学習データ全体」を縛るが、1 ミニバッチが確保する 3 次元テンソルの
#: ピークサイズは別の変数の積（`batch_size`・`max_nnz`・`n_classes`）で決まり、
#: これらすべてを個別に上限内へ収めても積が跳ね上がりうる（例:
#: batch_size=4096・max_nnz=4096*7=28672・n_classes=16 だと
#: 4096*28672*16 ≈ 1.88e9 要素 ≈ float32 で 7.5 GiB。順伝播の gather 結果と
#: 逆伝播用の勾配バッファで少なくとも 2 倍の同時確保が起きうる）。学習ループ
#: 開始前（1 バッチも確保する前）にこの上限で fail-closed に拒否する
#: （`limit_exceeded`・exit 20。素の MLX 確保失敗による exit 70・OOM kill を防ぐ）。
#: 既定値は float32 換算で 1 要素あたり概算 8 bytes（順伝播+逆伝播の 2 倍見積もり）
#: として `MAX_TRAIN_RSS_BYTES`（既定 8 GiB）の一部（ここでは目安として
#: 1.5 GiB 程度）に収まる水準。
MAX_C1_BATCH_ELEMENTS = 200_000_000

#: `_build_vocabulary` が 1 チャンクあたりに生成する n-gram 窓要素数の目標上限
#: （セキュリティ監査 P2-1）。実際のチャンク件数（文書数）はこの値を
#: 「1 文書あたりの窓数の上限」（`ids_arr` の実際の列幅 × n の種類数）で
#: 割って動的に決める。値が小さいほど 1 チャンクの一時配列のピークメモリは
#: 下がるが、チャンク数（Python ループの反復回数）は増える。既定値は
#: int64（8 bytes/要素）換算で 1 チャンクあたり概算 32 MiB 程度に収まる水準。
MAX_C1_VOCAB_CHUNK_WINDOW_ELEMENTS = 4_000_000
