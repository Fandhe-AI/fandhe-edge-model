//! データ契約層で扱うファイルの資源上限（REQ-39「資源の上限」）。

/// 評価データ 1 件（1 ファイル）あたりの読み込み上限バイト数。
///
/// PoC-16・学習ワーカー側の `MAX_TRAIN_DATA_BYTES`（学習データの読み込み上限）を
/// 準用した仮置きの値であり、証拠種別は「仮置き・trainer 準用」（実機での容量計測
/// 済みの値ではない）。評価契約の資源上限（REQ-39）の確定値は、データ契約層の
/// 検査タスク（TASK-16.x）で改めて見直す想定。
pub const MAX_EVAL_DATA_BYTES: u64 = 64 * 1024 * 1024;
