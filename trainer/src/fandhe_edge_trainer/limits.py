"""学習ワーカーが読み込む外部入力の資源上限（REQ-39）を 1 箇所に集約する。

**暫定値であることの注記**: 以下はすべて学習ワーカー固有の暫定値であり、
推論ガード層（Rust 側）向けに REQ-39 が定義する資源上限とは別物として扱う
（REQ-39 は推論ガード層向けの暫定値を定義しており、本ワーカーへの適用範囲は
オーナー確認待ちの論点。ここでは学習ワーカー固有の値として暫定的に定める。
値そのものもレビューで指摘された妥当な水準の暫定案であり、オーナー確認前提）。
"""

from __future__ import annotations

#: 学習リクエスト JSON ファイルの最大バイト数。
MAX_REQUEST_BYTES = 1 * 1024 * 1024

#: 学習データ（JSONL）ファイルの最大バイト数（累積読み取りバイト数で判定する）。
MAX_TRAIN_DATA_BYTES = 64 * 1024 * 1024

#: 学習データの最大件数（行数ではなく、検証を通過した examples の件数）。
MAX_TRAIN_EXAMPLES = 200_000

#: 学習データ 1 行あたりの最大バイト数（JSON パース・NFKC 正規化の前に検査する）。
MAX_TRAIN_LINE_BYTES = 64 * 1024

#: label_order の最小・最大件数。
MIN_LABELS = 2
MAX_LABELS = 1024

#: 1 ラベルあたりの最大 UTF-8 バイト数。
MAX_LABEL_BYTES = 256

#: max_bytes（バイト入力の最大長）の許容範囲。
MIN_MAX_BYTES = 1
MAX_MAX_BYTES = 4096

#: seed の許容範囲（`mx.random.seed`・`numpy.random.default_rng` が受け付ける
#: 非負 32 bit 符号なし整数の範囲に合わせる）。
MIN_SEED = 0
MAX_SEED = 2**32 - 1

# --------------------------------------------------------------------------
# kind="c3" のアーキテクチャ・ハイパーパラメータ上限。
#
# 本来は「新しい kind を追加する際に共通コア・既存の種類の実装を改変しない」
# （拡張点の閉じ方）という方針上、kind 固有の上限は `kinds/c3.py` 側に置く方が
# 望ましい。ここへ集約しているのはレビュー指摘（「資源上限は名前付き定数として
# limits.py へ集約する」）に従うためで、C1 等の追加時にこのセクションが
# 肥大化するようなら kind ごとの上限モジュールへ分割することを検討する。
# --------------------------------------------------------------------------
MAX_C3_EMB = 1024
MAX_C3_FILTERS = 1024
MIN_C3_WIDTHS = 1
MAX_C3_WIDTHS = 8
MAX_C3_WIDTH_VALUE = 31
MAX_C3_EPOCHS = 1000
MAX_C3_BATCH_SIZE = 4096
MAX_C3_LR = 1.0
MAX_C3_WEIGHT_DECAY = 1.0
